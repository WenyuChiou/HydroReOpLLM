"""Native observed-boundary reach simulation and daily period evaluation.

Purpose and data flow
---------------------
Validated weather and observed upstream daily mean flow (m3/s) drive
a native reach whose upstream routing outlet is preserved exactly. Local
catchment runoff remains generated by HydroCNHS. Separate evaluation splits
aligned daily series into ordered inclusive periods and reports gauge metrics
with explicit missing/excluded observations.

Dependencies and side effects
-----------------------------
Reads accepted core pins and lazily loads HydroCNHS/NumPy for simulation.
Uses a copied native model and assigned boundary/route kernels; one trailing
zero preserves the pinned engine's final physical kernel weight. Native runtime
may write its own logs; no reservoir decision, calibration or provider call occurs.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from copy import deepcopy
from datetime import date
import hashlib
import json
import math
from pathlib import Path


def _observed_flows(values: Sequence[object], length: int) -> list[float]:
    if len(values) != length:
        raise ValueError("upstream_cms must have the same length as weather dates")
    result: list[float] = []
    for index, value in enumerate(values):
        if isinstance(value, (bool, str, bytes)):
            raise TypeError(f"upstream_cms[{index}] must be a number")
        try:
            number = float(value)
        except (TypeError, ValueError, OverflowError) as exc:
            raise TypeError(f"upstream_cms[{index}] must be a number") from exc
        if not math.isfinite(number):
            raise ValueError(f"upstream_cms[{index}] must be finite")
        if number < 0.0:
            raise ValueError(f"upstream_cms[{index}] must be nonnegative")
        result.append(number)
    return result


def _verify_native_core(runtime_root: Path, package: Path) -> None:
    pin = runtime_root / "environment/hydrocnhs-core.json"
    core = json.loads(pin.read_bytes())
    for item in core["files"]:
        raw = (package / item["path"]).read_bytes().replace(b"\r\n", b"\n")
        if hashlib.sha256(raw).hexdigest() != item["normalized_sha256"]:
            raise ValueError("installed HydroCNHS core differs from its accepted pin")


def simulate_observed_boundary(weather, boundary_node, upstream_cms, runtime_root):
    """Run native reach hydrology while preserving observed upstream outlet flow.

    Parameters
    ----------
    weather : mapping
        Validated daily load_weather result; precipitation in mm/day, temperature
        in degrees C and PET in cm/day.
    boundary_node : str
        Native Routing outlet also declared as a zero_flow_node. Its route must
        contain no upstream runoff sources other than itself.
    upstream_cms : sequence of float
        Finite nonnegative observed daily flow in m3/s, one value per weather day.
    runtime_root : str or pathlib.Path
        Root containing native working directory and accepted core hash manifest.

    Returns
    -------
    dict
        Dates, local runoff and routed means in m3/s, canonical dimensionless
        unit hydrographs keyed by (source, outlet), and routing compatibility
        metadata. The boundary output equals the supplied observed series.

    Raises
    ------
    TypeError
        Boundary name or observed flow types are invalid.
    ValueError
        Boundary topology, observed coverage/values or native core pins are invalid.
    ArithmeticError
        Native routing changes the assigned boundary/kernel or yields invalid flow.
    OSError
        Accepted runtime pin/source files cannot be read.

    Notes
    -----
    The boundary is already routed flow at that outlet. Removing only its
    self-route prevents a second routing pass or in-place overwrite. Precipitation
    is divided by 10 for native cm/day; native source bytes stay unchanged.
    """
    if not isinstance(boundary_node, str) or not boundary_node:
        raise TypeError("boundary_node must be a native outlet name")
    dates = weather["dates"]
    observed = _observed_flows(upstream_cms, len(dates))
    zero = weather["zero"]
    if boundary_node not in zero:
        raise ValueError("boundary_node must be declared as a zero_flow_node")
    routing = weather["model"].get("Routing")
    if not isinstance(routing, dict) or boundary_node not in routing:
        raise ValueError("boundary_node must be a native Routing outlet")
    if any(source != boundary_node for source in routing[boundary_node]):
        raise ValueError("observed boundary must start the modeled reach, without upstream runoff paths")

    # Keep the costly native stack out of configuration-only callers.
    import hydrocnhs
    import numpy as np

    root = Path(runtime_root)
    package = Path(hydrocnhs.__file__).resolve().parent
    _verify_native_core(root, package)
    from hydrocnhs.routing import form_UH_Lohmann

    model_config = deepcopy(weather["model"])
    model_config["Path"] = {"WD": str(root), "Modules": ""}
    # The observed series is already flow at this routing outlet.  Keep it as
    # an upstream source for every native downstream route, but do not let the
    # engine route the outlet into itself and overwrite assigned_Q in-place.
    del model_config["Routing"][boundary_node]
    series = {
        unit: np.asarray([weather["samples"][unit][day] for day in dates])
        for unit in weather["units"]
    }
    assigned = {unit: np.zeros(len(dates)) for unit in zero}
    # Observed m3/s enters once at the reach boundary, without new local runoff.
    assigned[boundary_node] = np.asarray(observed)
    kernels, assigned_kernels = {}, {}
    for outlet, sources in model_config["Routing"].items():
        for source, route in sources.items():
            parameters = deepcopy(route["Pars"])
            if source in assigned:
                parameters.update(GShape=None, GScale=None)
            kernel = np.asarray(form_UH_Lohmann(route["Inputs"], parameters), dtype=float)
            if kernel.ndim != 1 or not len(kernel) or not np.isfinite(kernel).all() or (kernel < -1e-12).any() or not np.isclose(kernel.sum(), 1, atol=1e-12, rtol=0):
                raise ArithmeticError("Native routing kernel is invalid before assignment")
            kernels[(source, outlet)] = kernel.copy()
            # The pinned native routing step omits the last array element.
            # One trailing zero retains every physical weight, including a
            # single-weight impulse, through the public assigned_UH interface.
            # Native source bytes and the canonical kernel remain unchanged.
            assigned_kernels[(source, outlet)] = np.pad(kernel, (0, 1))
    model = hydrocnhs.Model(
        model_config,
        name="HydroReOpLLMObservedBoundary",
        rn_gen=hydrocnhs.create_rn_gen(7),
        paral_setting={
            "verbose": 0,
            "cores_pet": 1,
            "cores_formUH": 1,
            "cores_runoff": 1,
        },
    )
    routed = model.run(
        temp={unit: values[:, 1] for unit, values in series.items()},
        prec={unit: values[:, 0] / 10 for unit, values in series.items()},
        pet={unit: values[:, 2] for unit, values in series.items()},
        assigned_Q=assigned,
        assigned_UH=assigned_kernels,
        disable=True,
    )
    if boundary_node not in routed or not np.array_equal(np.asarray(routed[boundary_node]), np.asarray(observed)):
        raise ArithmeticError("native routing changed the observed upstream boundary")
    runoff = {unit: model.dc.Q_runoff[unit] for unit in weather["units"]}
    if set(model.dc.UH_Lohmann) != set(assigned_kernels) or any(
        not np.array_equal(np.asarray(model.dc.UH_Lohmann[key]), expected)
        for key, expected in assigned_kernels.items()
    ):
        raise ArithmeticError("Native routing changed an assigned kernel")
    if len(dates) != len(observed):
        raise ArithmeticError("native hydrology output dates differ from the observed boundary")
    for values in [*routed.values(), *runoff.values()]:
        output = np.asarray(values)
        if (
            output.shape != (len(dates),)
            or not np.isfinite(output).all()
            or (output < 0).any()
        ):
            raise ArithmeticError("native hydrology produced invalid daily flow")
    return {
        "dates": list(dates),
        "runoff": runoff,
        "routed": routed,
        "unit_hydrographs": kernels,
        "routing_compatibility": {
            "method": "native canonical UH plus one trailing zero via assigned_UH",
            "reason": "pinned run_step_Lohmann omits the final array element",
            "native_source_modified": False,
            "physical_weights_changed": False,
            "padding_weights_per_route": 1,
        },
    }


def _period_date(value: object, label: str) -> date:
    if not isinstance(value, str):
        raise TypeError(f"{label} must be an ISO date string")
    try:
        parsed = date.fromisoformat(value)
    except ValueError as exc:
        raise ValueError(f"{label} must be a valid ISO date") from exc
    if parsed.isoformat() != value:
        raise ValueError(f"{label} must use YYYY-MM-DD format")
    return parsed


def evaluate_periods(
    dates,
    simulated_cms,
    observed_cms,
    periods,
    *,
    eligible=None,
):
    """Evaluate ordered nonoverlapping inclusive periods on a shared daily grid.

    Parameters
    ----------
    dates : sequence of str
        Nonempty consecutive canonical YYYY-MM-DD dates.
    simulated_cms : sequence of float
        Finite simulated daily flows in m3/s.
    observed_cms : sequence of float or None
        Aligned observations in m3/s; None marks missing data.
    periods : mapping of str to sequence of str
        In insertion order, nonempty phase names mapped to [start, end] inclusive
        dates present on the supplied grid. Periods may have gaps but not overlaps.
    eligible : sequence of bool, optional
        Shared per-day inclusion mask; sliced consistently into each period.

    Returns
    -------
    dict of str to dict
        Per-phase start/end dates and evaluate_daily_flows metrics, counts and
        undefined-metric reasons. Flow errors retain m3/s units.

    Raises
    ------
    TypeError
        Date, phase, flow or mask types are invalid.
    ValueError
        Shared series are invalid or period bounds are absent, reversed,
        overlapping or out of order.

    Notes
    -----
    All input days are validated, including days outside requested periods.
    The inclusive end index is converted to an exclusive Python slice stop.
    """
    from .downstream import _daily_dates, evaluate_daily_flows

    parsed_dates = _daily_dates(dates)
    # Validate all supplied values, including days outside requested intervals.
    evaluate_daily_flows(dates, simulated_cms, observed_cms, eligible=eligible)
    if not isinstance(periods, Mapping) or not periods:
        raise ValueError("periods must be a nonempty phase mapping")

    positions = {item: index for index, item in enumerate(parsed_dates)}
    previous_end: date | None = None
    bounds: list[tuple[object, str, str, int, int]] = []
    for phase, interval in periods.items():
        if not isinstance(phase, str) or not phase:
            raise TypeError("period phase names must be nonempty strings")
        if (
            isinstance(interval, (str, bytes))
            or not isinstance(interval, Sequence)
            or len(interval) != 2
        ):
            raise ValueError(f"period {phase!r} must contain [start, end]")
        start_text, end_text = interval
        start = _period_date(start_text, f"period {phase!r} start")
        end = _period_date(end_text, f"period {phase!r} end")
        if start > end:
            raise ValueError(f"period {phase!r} start must not follow its end")
        if start not in positions or end not in positions:
            raise ValueError(f"period {phase!r} must be bounded by supplied dates")
        if previous_end is not None and start <= previous_end:
            raise ValueError("periods must be ordered and nonoverlapping")
        previous_end = end
        # Add one to retain the declared final calendar day in a half-open slice.
        bounds.append((phase, start_text, end_text, positions[start], positions[end] + 1))

    result: dict[str, dict[str, object]] = {}
    for phase, start, end, first, stop in bounds:
        phase_eligible = None if eligible is None else eligible[first:stop]
        metrics = evaluate_daily_flows(
            dates[first:stop],
            simulated_cms[first:stop],
            observed_cms[first:stop],
            eligible=phase_eligible,
        )
        result[phase] = {"start": start, "end": end, **metrics}
    return result
